"""Generate the validation report.

    python scripts/validate.py --source generate --scale starter     # baseline AND baseline+anomalies, no database needed
    python scripts/validate.py --source db                            # validate what is loaded in PostgreSQL

Writes docs/validation_report.md (+ data/processed/validation_<label>.json with every error and record id).
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
for p in (ROOT, ROOT / "backend"):
    sys.path.insert(0, str(p))

from app.validation.validator import validate  # noqa: E402

HEADER = """# Validation report

Generated by `scripts/validate.py`. The validation module (`backend/app/validation/`) runs {n} validations over every
table: primary keys, foreign keys, allowed enums, ID conventions, timestamp ordering, machine-state transitions,
possible interlock combinations, acknowledgement timelines, derived values, incident traceability and lifecycle,
corrective-action verification, duplicates, arithmetic reconciliation, relationship cardinality.

*Passed / failed* refers to validations. Business-rule failures on the injected dataset are the **expected** consequence
of the five labelled anomalies (see `business_rules.md` section 5); the clean baseline must pass every validation.
The anomaly detectors do not read ground truth; their comparison with ground truth is in the metrics report.

"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--source", choices=["generate", "db"], default="generate")
    ap.add_argument("--scale", choices=["starter", "full"], default="starter")
    ap.add_argument("--out", type=Path, default=ROOT / "docs" / "validation_report.md")
    args = ap.parse_args()
    sections, jsons = [], {}
    if args.source == "generate":
        from data_generator.config import from_scale
        from data_generator.generate import generate_with_anomalies
        base, final = generate_with_anomalies(from_scale(args.scale))
        for label, title, ds in (("baseline", f"Clean baseline ({args.scale} scale, seed {base.cfg.seed})", base),
                                 ("with_anomalies", f"Baseline + injected anomalies ({args.scale} scale)", final)):
            rep = validate(ds.tables)
            sections.append(rep.to_markdown(title))
            jsons[f"{args.scale}_{label}"] = rep.to_dict()
            s = rep.summary()
            print(f"{title}: {s['validations_passed']}/{s['validations_run']} passed, failed={s['failed_validation_ids']}, "
                  f"anomalies={s['anomalies_detected']}")
    else:
        from app.core.config import get_settings
        from app.core.database import make_engine
        from sqlalchemy.orm import Session
        from app.services.validation_service import run_validation
        db = get_settings().db_name
        with Session(make_engine(db)) as session:
            rep = run_validation(session)
        sections.append(rep.to_markdown(f"Database '{db}'"))
        jsons[f"db_{db}"] = rep.to_dict()
        s = rep.summary()
        print(f"database {db}: {s['validations_passed']}/{s['validations_run']} passed, failed={s['failed_validation_ids']}, "
              f"anomalies={s['anomalies_detected']}")
    first = next(iter(jsons.values()))
    args.out.write_text(HEADER.format(n=len(first["checks"])) + "\n".join(sections), encoding="utf-8")
    proc = ROOT / "data" / "processed"
    proc.mkdir(parents=True, exist_ok=True)
    for label, data in jsons.items():
        (proc / f"validation_{label}.json").write_text(json.dumps(data, indent=2), encoding="utf-8")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
